#!/usr/bin/env python3
"""Copy a built pret/pokepinballrs tree and adapt it for the port.

Nothing from the game lives in this repository. The decomp tree is fetched
and built on the user's machine (and checked against their own ROM); this
script copies it to a scratch directory and edits it there. Edits are keyed
on symbol names only, and each one must match exactly once, so an upstream
change fails loudly instead of silently building something else.
"""
import os, re, shutil, sys


def die(msg):
    sys.exit("prepare.py: " + msg)


def rsub(path, pattern, repl, count=1, flags=re.M):
    with open(path, encoding="utf-8") as f:
        s = f.read()
    s2, n = re.subn(pattern, repl, s, flags=flags)
    if n == 0 or (count and n != count):
        die(f"{path}: pattern matched {n} times, wanted {count}: {pattern[:50]!r}")
    with open(path, "w", encoding="utf-8") as f:
        f.write(s2)


# ---------------------------------------------------------------------------
# Tall table: the whole board is shown at once (top and bottom screen), so
# nothing may depend on where the camera is. World sprites carry a large bias
# in their screen Y (PORT_WB): the port sees from that bias which sprites are
# part of the table and which are fixed on-screen (menus, score).
# ---------------------------------------------------------------------------
def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write(path, s):
    with open(path, "w", encoding="utf-8") as f:
        f.write(s)


def scan_expr(s, i):
    """Index of the ';' ending the expression that starts at i (depth 0)."""
    depth = 0
    while i < len(s):
        c = s[i]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == ";" and depth == 0:
            return i
        i += 1
    die("unterminated expression")


def hook_oam_y(s):
    """gOamBuffer[i].y = e;  ->  PortOamYSet(&gOamBuffer[i], (e));   (also += and the pointer forms)"""
    ptrs = set(re.findall(r"struct OamData \*(\w+)", s))
    out, i, n = [], 0, 0
    head = re.compile(r"(gOamBuffer\[)|\b(" + "|".join(sorted(ptrs)) + r")->y\b" if ptrs else r"(gOamBuffer\[)")
    while True:
        m = head.search(s, i)
        if not m:
            out.append(s[i:])
            break
        j = m.end()
        if m.group(1):                                   # find the matching ]
            depth = 1
            while depth:
                depth += {"[": 1, "]": -1}.get(s[j], 0)
                j += 1
            target = "&" + s[m.start():j]
            if not s.startswith(".y", j) or re.match(r"\w", s[j + 2:j + 3]):
                out.append(s[i:j]); i = j; continue
            j += 2
        else:
            target = m.group(2)
        op = re.match(r"\s*(\+=|-=|=)(?!=)\s*", s[j:])
        if not op:
            out.append(s[i:j]); i = j; continue
        k = j + op.end()
        e = scan_expr(s, k)
        fn = {"=": "PortOamYSet", "+=": "PortOamYAdd", "-=": "PortOamYSub"}[op.group(1)]
        out.append(s[i:m.start()] + f"{fn}({target}, ({s[k:e]}))")
        i = e
        n += 1
    return "".join(out), n


PORT_SONG_C = r"""// Generated by the port: song pointers in saved games, made independent of the build.
#include "global.h"
#include "m4a.h"
#include "constants/bg_music.h"

#define PORT_SONG_TAG 0x534E0000u
#define PORT_SONG_N @N@

const struct SongHeader *PortSongToSave(const struct SongHeader *h)
{
    int i;
    for (i = 0; i < PORT_SONG_N; i++)
        if (gSongTable[i].header == h)
            return (const struct SongHeader *)(PORT_SONG_TAG | i);
    return NULL;
}

const struct SongHeader *PortSongFromSave(const struct SongHeader *h, int field)
{
    u32 v = (u32)h;
    int i;
    if ((v & 0xFFFF0000u) == PORT_SONG_TAG && (v & 0xFFFF) < PORT_SONG_N)
        return gSongTable[v & 0xFFFF].header;
    for (i = 0; i < PORT_SONG_N; i++)
        if (gSongTable[i].header == h)
            return h;
    // a pointer from another build: the table's own music is the best guess
    return gSongTable[field == FIELD_SAPPHIRE ? MUS_FIELD_SAPPHIRE : MUS_FIELD_RUBY].header;
}

// The saved game also holds two pointers into itself (which ball is live). They are
// re-pointed at this build's copy; the game state sits on a 16-byte boundary in every build.
static struct BallState *FixBall(struct BallState *b)
{
    u32 off = (u32)((u8 *)gCurrentPinballGame->ballStates - (u8 *)gCurrentPinballGame);
    if ((((u32)b - off - sizeof(struct BallState)) & 0xF) == 0 && (((u32)b - off) & 0xF) != 0)
        return &gCurrentPinballGame->ballStates[1];
    return &gCurrentPinballGame->ballStates[0];
}

void PortFixSavedPointers(void)
{
    gCurrentPinballGame->ball = FixBall(gCurrentPinballGame->ball);
    gCurrentPinballGame->cameraBall = FixBall(gCurrentPinballGame->cameraBall);
}
"""


def tall_patches(p):
    g = p("include/global.h")
    rsub(g, r"^#endif // GUARD_GLOBAL_H", """/* ---- port: tall table ---- */
extern unsigned char gPortTall;
void PortOamYSet(void *o, int v);
void PortOamYAdd(void *o, int v);
void PortOamYSub(void *o, int v);
#define PORT_WB 2048
#define PORT_CYO (gPortTall ? -PORT_WB : gCurrentPinballGame->cameraYOffset)
#define PORT_CBY (gPortTall ? -PORT_WB : gCurrentPinballGame->cameraBaseY)
#define PORT_CSO (gPortTall ? 0 : gCurrentPinballGame->cameraScrollOffset)
#define PORT_CYA (gPortTall ? 0 : gCurrentPinballGame->cameraYAdjust)
#define PORT_SHY (gPortTall ? 0 : gCurrentPinballGame->screenShakeY)
#define PORT_HI(n) (gPortTall ? PORT_WB + 480 + ((n) - 160) : (n))
#define PORT_LO(n) (gPortTall ? PORT_WB + (n) : (n))
#endif // GUARD_GLOBAL_H""")

    total_y = 0
    for fn in sorted(os.listdir(p("src"))):
        if not fn.endswith(".c"):
            continue
        path = p("src", fn)
        t = read(path)
        t0 = t
        t, ny = hook_oam_y(t)
        total_y += ny
        # camera reads inside sprite maths (assignments to the camera itself stay)
        t = re.sub(r"gCurrentPinballGame->cameraYOffset\b(?!\s*=[^=])", "PORT_CYO", t)
        if fn in ("all_board_process7.c", "kecleon_process3.c"):
            t = re.sub(r"gCurrentPinballGame->cameraBaseY\b(?!\s*[-+*]?=(?!=))", "PORT_CBY", t)
            t = re.sub(r"gCurrentPinballGame->cameraScrollOffset\b(?!\s*[-+*]?=(?!=))", "PORT_CSO", t)
            t = re.sub(r"gCurrentPinballGame->cameraYAdjust\b(?!\s*[-+*]?=(?!=))", "PORT_CYA", t)
        if fn == "all_board_process7.c":
            t = re.sub(r"gCurrentPinballGame->screenShakeY\b", "PORT_SHY", t)
        # off-screen tests on a sprite group's baseY: the table is taller than the screen
        t = re.sub(r"(\bbaseY\s*(?:>=|>)\s*)(1[89]0|200)\b", r"\1PORT_HI(\2)", t)
        t = re.sub(r"(\bbaseY\s*(?:<=|<)\s*)(-\d+)\b", r"\1PORT_LO(\2)", t)
        # entities are switched on (and drawn) only while the camera is near them: keep them all going
        num = r"(?:0[xX][0-9a-fA-F]+|\d+)"
        t = re.sub(r"(gCurrentPinballGame->cameraYViewport\s*[<>]\s*" + num + r")", r"(gPortTall || \1)", t)
        t = re.sub(r"(\b" + num + r"\s*<\s*gCurrentPinballGame->cameraYViewport\b)", r"(gPortTall || \1)", t)
        if t != t0:
            write(path, t)
    if total_y < 250:
        die(f"sprite Y rewrite matched only {total_y} places")

    u = p("src/util.c")
    rsub(u, r"DmaCopy16\(3, gEmptyOamData, oamData, sizeof\(gEmptyOamData\)\);", "PortOamClear();")
    rsub(u, r"oamSimple->yOffset = oamData\[0\] & 0xFF;", "oamSimple->yOffset = gPortTall ? (s8)(oamData[0] & 0xFF) : (oamData[0] & 0xFF);")
    rsub(u, r"\A", "void PortOamClear(void);\n")
    rsub(p("src/main.c"), r"DmaCopy32\(3, gOamBuffer, OAM, OAM_SIZE\);", "if (!((gMain.mainState == STATE_GAME_MAIN || gMain.mainState == STATE_GAME_IDLE) && gMain.selectedField <= FIELD_SAPPHIRE)) gPortTall = 0;\n    PortOamCopy();")
    # Saved games keep a pointer to the song that was playing. Addresses differ between builds of
    # the port, so the save stores the song's number instead and old pointers are recognised.
    n_songs = len(re.findall(r"^\s*song\s", read(p("sound/song_table.inc")), flags=re.M))
    if n_songs < 100:
        die("song table not found")
    write(p("src/port_song.c"), PORT_SONG_C.replace("@N@", str(n_songs)))
    rsub(p("src/save_and_restore_game.c"),
         r"gCurrentPinballGame->savedBgmSongHeader = gMPlayInfo_BGM\.songHeader;",
         "gCurrentPinballGame->savedBgmSongHeader = PortSongToSave(gMPlayInfo_BGM.songHeader);")
    rsub(p("src/save_and_restore_game.c"),
         r"(ReadSramFast\([^;]*gCurrentPinballGame, sizeof\(\*gCurrentPinballGame\)\);)",
         r"\1\n        PortFixSavedPointers();")
    rsub(p("src/save_and_restore_game.c"), r"\A",
         "const struct SongHeader *PortSongToSave(const struct SongHeader *h);\nvoid PortFixSavedPointers(void);\n")
    g = p("src/all_board_pinball_game_main.c")
    rsub(g, r"MPlayStart\(&gMPlayInfo_BGM, gCurrentPinballGame->savedBgmSongHeader\);",
         "MPlayStart(&gMPlayInfo_BGM, PortSongFromSave(gCurrentPinballGame->savedBgmSongHeader, gMain.selectedField));")
    rsub(g, r"\A", "const struct SongHeader *PortSongFromSave(const struct SongHeader *h, int field);\n")
    rsub(p("src/main.c"), r"\A", "void PortOamCopy(void);\nvoid PortUpdateTall(int on, int field, int ballY);\nvoid LayoutStats(unsigned lo, unsigned hi, int lives, int coins);\n")
    rsub(p("src/main.c"), r"^(\s*)gMainFuncs\[gMain.mainState\]\(\);",
         r"\1PortUpdateTall((gMain.mainState == STATE_GAME_MAIN || gMain.mainState == STATE_GAME_IDLE) && gMain.selectedField <= FIELD_SAPPHIRE, gMain.selectedField, ((gMain.mainState == STATE_GAME_MAIN || gMain.mainState == STATE_GAME_IDLE) && gCurrentPinballGame && gCurrentPinballGame->ball) ? gCurrentPinballGame->ball->positionQ0.y : -1);\n\1if ((gMain.mainState == STATE_GAME_MAIN || gMain.mainState == STATE_GAME_IDLE) && gCurrentPinballGame) LayoutStats(gCurrentPinballGame->scoreLo, gCurrentPinballGame->scoreHi, gCurrentPinballGame->numLives, gCurrentPinballGame->coins);\n\1gMainFuncs[gMain.mainState]();")


def main():
    src, dst = sys.argv[1], sys.argv[2]
    if os.path.exists(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst, symlinks=True,
                    ignore=shutil.ignore_patterns(".git", "build", "*.gba", "*.elf", "*.map", "tools"))
    p = lambda *a: os.path.join(dst, *a)

    # --- GBA memory regions become port-owned arrays -------------------
    d = p("include/gba/defines.h")
    rsub(d, r"^(#define PLTT\s+)\w+$", r"\1GBA_MEM(gGbaPltt)")
    rsub(d, r"^(#define VRAM\s+)\w+$", r"\1GBA_MEM(gGbaVram)")
    rsub(d, r"^(#define OAM\s+)\w+$", r"\1GBA_MEM(gGbaOam)")
    rsub(d, r"^(#define GUARD_GBA_DEFINES)$", r"""\1

#ifdef PORT_ASM
#define GBA_MEM(sym) sym
#else
#include <stdint.h>
extern unsigned char gGbaPltt[], gGbaVram[], gGbaOam[], gGbaIo[], gGbaSram[];
#define GBA_MEM(sym) ((uintptr_t)(sym))
#endif""")
    rsub(p("include/gba/io_reg.h"), r"^(#define REG_BASE\s+)\w+", r"\1GBA_MEM(gGbaIo)")
    rsub(p("include/agb_sram.h"), r"^(#define SRAM\s+)\w+", r"\1GBA_MEM(gGbaSram)")

    c = p("include/gba/gba_c_defines.h")
    rsub(c, r"^#define IWRAM_DATA .*$", "#define IWRAM_DATA")
    rsub(c, r"^#define EWRAM_DATA .*$", "#define EWRAM_DATA")
    rsub(c, r"^#define SOUND_INFO_PTR .*$",
         "extern struct SoundInfo *gGbaSoundInfoPtr;\n#define SOUND_INFO_PTR gGbaSoundInfoPtr")
    rsub(c, r"^#define INTR_CHECK .*$", "extern unsigned short gGbaIntrCheck;\n#define INTR_CHECK gGbaIntrCheck")
    rsub(c, r"^#define INTR_VECTOR .*$", "extern void *gGbaIntrVector;\n#define INTR_VECTOR gGbaIntrVector")

    # newlib makes int32_t a long; the game mixes int and s32 freely
    t = p("include/gba/types.h")
    rsub(t, r"^typedef uint32_t\s+u32;", "typedef unsigned int u32;")
    rsub(t, r"^typedef int32_t\s+s32;", "typedef int s32;")

    # --- DMA: registers are plain memory now, so do the transfer in a call
    rsub(p("include/gba/macro.h"), r"^#define DmaSet\(.*?^\}", """void GbaDmaSet(int dmaNum, const void *src, void *dest, unsigned int control);
#define DmaSet(dmaNum, src, dest, control) \\
    GbaDmaSet(dmaNum, (const void *)(src), (void *)(dest), (unsigned int)(control))""",
         flags=re.M | re.S)

    # --- main loop: no interrupt-vector copy, give the port a per-loop hook
    mc = p("src/main.c")
    rsub(mc, r"^.*IntrMain_Buffer.*\n", "", count=2)
    rsub(mc, r"^(\s*)MainLoopIter\(\);\n(\s*\}\s*\n\})", r"\1MainLoopIter();\n\1PortMainLoopTick();\n\2")
    rsub(mc, r"\A", "void PortMainLoopTick(void);\n")

    # --- Game Boy Player detection splash is skipped (no such hardware)
    rsub(p("src/gbplayer.c"), r"= CheckGameBoyPlayer\(\);", "= 0; (void)CheckGameBoyPlayer;")

    # --- Sound engine. The game's own sequencer and mixer (src/m4a_1.s) are
    # ARM code and run as they are on the 3DS CPU; they are assembled from the
    # user's tree, with only their fixed addresses pointed at the port.
    a = p("src/m4a.c")
    rsub(a, r"^.*SoundMainRAM_Buffer, sizeof.*\n", "")
    rsub(a, r'asm\("swi 0x2A"\);', "MPlayJumpTableCopy(gMPlayJumpTable);")
    rsub(a, r"^\s*while \(\*\(vu8 \*\)REG_ADDR_VCOUNT [!=]= 159\)\s*\n\s*;\n", "", count=2)
    rsub(a, r"^#define BSS_CODE .*$", "#define BSS_CODE")
    rsub(a, r"^(\s*)SoundMain\(\);", r"\1PortAudioBeforeMix(); SoundMain(); PortAudioAfterMix();")
    rsub(a, r"\A", "void PortAudioBeforeMix(void); void PortAudioAfterMix(void);\n")

    # linker-script constants: a relocatable 3DS binary cannot carry absolute symbols
    ld = open(p("ld_script.txt"), encoding="utf-8").read()
    h = p("include/gba/m4a_internal.h")
    rsub(h, r"^(#define NUM_MUSIC_PLAYERS) .*$", r"\1 " + re.search(r"gNumMusicPlayers = (\w+);", ld).group(1))
    rsub(h, r"^(#define MAX_LINES) .*$", r"\1 " + re.search(r"gMaxLines = (\w+);", ld).group(1))

    gc = p("constants/gba_constants.inc")
    rsub(gc, r"^(\s*\.set SOUND_INFO_PTR,\s*)\w+", r"\1gGbaSoundInfoPtr")
    rsub(gc, r"^(\s*\.set REG_BASE,\s*)\w+", r"\1gGbaIo")
    m1 = p("src/m4a_1.s")
    rsub(m1, r"SoundMainRAM_Buffer \+ 1", "SoundMainRAM")      # the mixer runs in place, not from a RAM copy
    # 3dsxtool only accepts relocations on 4-byte boundaries; pad before calls
    rsub(m1, r"^(\s*bl\s)", r"\t.balign 4\n\1", count=0)
    rsub(m1, r"^chk_adr_r2:\n", "chk_adr_r2:\n\tbx lr\n")      # address guard assumes the GBA memory map

    # --- Song data embeds jump targets at odd addresses, which a relocatable
    # 3DS binary cannot fix up. Leave a blank there and list (place, target)
    # pairs in an aligned table; the port fills the blanks in at start-up.
    sd = p("data/sound_data.s")
    rsub(sd, r"\A\s*\.section \.rodata", "\t.section .data")
    songs = p("sound/songs")
    fix = []
    for fn in sorted(os.listdir(songs)):
        if not fn.endswith(".s"):
            continue
        out, jump = [], False
        for line in open(os.path.join(songs, fn), encoding="utf-8"):
            code = line.split("@")[0]
            mm = re.match(r"^(\s*)\.word\s+(\w+)\s*$", code)
            if mm and jump:
                lab = f"gPortSongFix_{len(fix)}"
                fix.append((lab, mm.group(2)))
                line = f"{lab}:\n{mm.group(1)}.word 0\n"
            if code.strip():
                jump = bool(re.match(r"^\s*\.byte\s+(GOTO|PATT|REPT)\b", code))
            # song files live in the same writable section as the rest
            if re.match(r"^\s*\.section\s+\.rodata", code):
                line = "\t.section .data\n"
            out.append(line)
        open(os.path.join(songs, fn), "w", encoding="utf-8").writelines(out)
    if len(fix) < 100:
        die("song jump rewrite matched suspiciously few targets")
    with open(sd, "a", encoding="utf-8") as f:
        f.write("\n\t.section .rodata\n\t.align 2\n\t.global gPortSongFixups\ngPortSongFixups:\n")
        for lab, target in fix:
            f.write(f"\t.word {lab}, {target}\n")
        f.write("\t.word 0, 0\n")

    tall_patches(p)

    # --- RAM variables are defined once, in the layout block below; a C
    # definition with a (zero) initialiser would be a second definition.
    for fn in os.listdir(p("src")):
        if fn.endswith(".c"):
            t = open(p("src", fn), encoding="utf-8").read()
            t2 = re.sub(r"^((?:EWRAM_DATA|IWRAM_DATA)[^=;\n]*?)\s*=[^;\n]*;", r"\1;", t, flags=re.M)
            if t2 != t:
                open(p("src", fn), "w", encoding="utf-8").write(t2)

    # --- RAM symbols: keep the GBA layout byte for byte (the game leans on
    # neighbouring buffers in a few places), as two contiguous .bss blocks.
    def ram(name, files):
        cap = name.capitalize()
        out = [f"\t.section .bss.{name},\"aw\",%nobits", "\t.balign 16", f"\t.global gGba{cap}", f"gGba{cap}:"]
        last = ""
        for fn in files:
            for line in open(p(fn), encoding="utf-8"):
                line = line.split("@")[0].rstrip()
                if not line.strip() or ".include" in line:
                    continue
                mm = re.match(r"^(\w+):\s*$", line)
                if mm:
                    last = mm.group(1)
                elif last == "gOamBuffer" and re.match(r"^\s*\.space\s+0x400\s*$", line):
                    line = "\t.space 0x1000"       # room for 512 sprites (tall table shows them all at once)
                out.append(f"\t.global {mm.group(1)}\n{mm.group(1)}:" if mm else line)
        out.append(f"\t.global gGba{cap}End\ngGba{cap}End:")
        return "\n".join(out) + "\n"

    with open(p("port_ram.s"), "w") as f:
        f.write(ram("ewram", ["sym_ewram.txt"]))
        f.write(ram("iwram", ["sym_bss.txt"]))
        f.write("\t.comm gMPlayInfo_SE3, 0x40, 4\n")     # the one common the C code leaves undefined


if __name__ == "__main__":
    main()
