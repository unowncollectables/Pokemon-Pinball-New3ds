#!/usr/bin/env python3
"""Turns an assembled PICA shader binary (.shbin) into a C source file with the bytes in an array.

usage: shbin2c.py in.shbin symbol > out.c
Gives `const unsigned char <symbol>[]` (4-byte aligned) and `const unsigned int <symbol>_size`.
"""
import sys

data = open(sys.argv[1], 'rb').read()
name = sys.argv[2]
out = ['/* generated by tools/shbin2c.py, do not edit */',
       'const unsigned char %s[] __attribute__((aligned(4))) = {' % name]
for i in range(0, len(data), 16):
    out.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
out.append('};')
out.append('const unsigned int %s_size = %d;' % (name, len(data)))
print('\n'.join(out))
